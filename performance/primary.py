class ResearchGap(RuntimeError):
    pass

def replace(source, old, new):
    if source.count(old) != 1:
        raise ValueError(f'Unexpected sealed engine text: {old}')
    return source.replace(old,new,1)

def compile_resume(replay, market):
    """Generate a continuation variant of the phase-1 function."""
    code=replay.__code__
    source=inspect.getsource(replay)
    source=replace(source,'partial=False):','partial=False,checkpoint=None):')
    if market=='US':
        source=replace(source,'    for i,date in enumerate(cal):','''    offset=0
    if checkpoint is not None:
        positions,blocked,cash,pending,nextid,offset=(
            checkpoint[k] for k in ('positions','blocked','cash','pending','nextid','sessions'))
    for i,date in enumerate(cal,start=offset):''')
        source=replace(source,'    before=max(d for d in groups if d<cal[0]);prev=groups[before]\n'
            '    pending={"signal_date":before,"exits":{},"entries":entry_candidates(prev,positions,{},blocked,cfg,strategy)}',
            '''    if checkpoint is None:
        before=max(d for d in groups if d<cal[0]);prev=groups[before]
        pending={"signal_date":before,"exits":{},"entries":entry_candidates(prev,positions,{},blocked,cfg,strategy)}''')
        source=replace(source,'holding_sessions=len(cal)-pos["entry_index"]','holding_sessions=offset+len(cal)-pos["entry_index"]')
        source=replace(source,'    return pd.DataFrame(daily).set_index("date"),pd.DataFrame(ledger),pd.DataFrame(actions),pd.DataFrame(openrows),pd.DataFrame(audits)',
            '''    state=dict(positions=positions,blocked=blocked,cash=cash,pending=pending,nextid=nextid,sessions=offset+len(cal))
    return pd.DataFrame(daily).set_index("date"),pd.DataFrame(ledger),pd.DataFrame(actions),pd.DataFrame(openrows),pd.DataFrame(audits),state''')
    else:
        source=replace(source,"    for date in sessions:",'''    prior_realized=0.
    offset=0
    if checkpoint is not None:
        cash,positions,blocked,pending_exits,pending_entries,pending_entry_signal,trade_id,prior_realized,offset=(
            checkpoint[k] for k in ('cash','positions','blocked','pending_exits','pending_entries','pending_entry_signal','trade_id','realized','sessions'))
    for date in sessions:''')
        source=replace(source,"    realized=sum(x['pnl_net'] for x in closed);unrealized=sum(x['unrealized_pnl'] for x in open_rows)",
            "    realized=prior_realized+sum(x['pnl_net'] for x in closed);unrealized=sum(x['unrealized_pnl'] for x in open_rows)")
        source=replace(source,'    return daily,a,c,o,pd.DataFrame(rejected)',
            '''    state=dict(cash=cash,positions=positions,blocked=blocked,pending_exits=pending_exits,pending_entries=pending_entries,
               pending_entry_signal=pending_entry_signal,trade_id=trade_id,realized=realized,sessions=offset+len(sessions))
    return daily,a,c,o,pd.DataFrame(rejected),state''')
    scope=dict(replay.__globals__)
    exec(compile(source,code.co_filename,'exec'),scope)
    return scope[replay.__name__]

def adapt_factory(phase, market, original):
    # The archived factory first applies the original A/B additions. Capture that
    # generated source, then change only the state boundary.
    captured=[]
    phase_exec=phase.__dict__.get('exec')
    builtin_exec=exec
    def capture(compiled, namespace):
        captured.append((compiled,namespace))
        builtin_exec(compiled,namespace)
    compile_src=compile
    sources=[]
    def remember(source,*args,**kwargs):
        sources.append(source)
        return compile_src(source,*args,**kwargs)
    try:
        phase.__dict__['exec']=capture
        phase.__dict__['compile']=remember
        reference=getattr(phase,f'build_{market.lower()}')(original)
    finally:
        if phase_exec is None:
            phase.__dict__.pop('exec',None)
        else:
            phase.__dict__['exec']=phase_exec
        phase.__dict__.pop('compile',None)
    assert len(sources)==len(captured)==1
    # inspect sees only the source generated by the factory via an isolated cache.
    import linecache
    key=f'<phase1-generated-{market}>'
    linecache.cache[key]=(len(sources[0]),None,sources[0].splitlines(keepends=True),key)
    scope=dict(captured[0][1])
    exec(compile(sources[0],key,'exec'),scope)
    return reference,compile_resume(scope[reference.__name__],market)

def restore(data, market):
    data=deepcopy(data)
    def dates(d,keys):
        for k in keys:
            if k in d:
                d[k]=pd.Timestamp(d[k]) if d[k] is not None else pd.NaT
    for p in data['positions'].values():
        dates(p,('entry_signal_date','entry_date','entry_financial_event','entry_financial_available_estimate',
                 'entry_macro_vintage','entry_macro_vintage_date'))
        if market=='US':
            # These columns are filing identifiers stored by the original engine.
            p['entry_max_input_filed']=p.get('entry_max_input_filed')
    if market=='US':
        dates(data['pending'],('signal_date',))
        for row in data['pending']['entries']:
            dates(row,('signal_date','financial_event_date','macro_vintage_date'))
    else:
        dates(data,('pending_entry_signal',))
        for req in data['pending_exits'].values():
            dates(req,('signal_date',))
    return data

def risk(nav):
    return dict(through=str(nav.index[-1].date()),start=str(nav.index[0].date()),sessions=len(nav),
        cumulative=float(nav.iloc[-1]-1),cagr=float(nav.iloc[-1]**(252/len(nav))-1) if len(nav)>=252 else None,
        max_drawdown=float((nav/nav.cummax().clip(lower=1)-1).min()),peak_nav=float(max(1.,nav.max())))

def write_json(path,value):
    path.write_text(json.dumps(js(value),ensure_ascii=False,indent=2,allow_nan=False)+'\n')

def validate_research_chain(paths, expected, markets=('US','TW')):
    """Reject missing per-session signal snapshots and unverifiable financial inputs."""
    from sheets_data import parse_envelope
    snapshots={m:{} for m in markets}
    rejected=[]
    for p in paths:
        release=json.loads(p.read_text())
        try:
            entry=parse_envelope(release['rows'],now=pd.Timestamp(release['snapshot']['generatedAt']).to_pydatetime())
        except (ValueError,KeyError,TypeError,OSError) as exc:
            rejected.append(dict(file=p.name,error=str(exc)))
            continue
        attempt=release['attempt']
        if attempt.get('status')!='published' or attempt.get('market') not in markets:
            continue
        m=attempt['market']
        block=entry['snapshot']['markets'][m]
        day=block['macro']['marketAsOf']
        if len(block['stocks'])!=MARKET_COUNTS[m] or not block['macro']['marketComplete']:
            raise ResearchGap(f'{m} {day} market batch incomplete')
        if day in snapshots[m] and snapshots[m][day]['batch']!=entry['batch']:
            raise ResearchGap(f'{m} {day} has conflicting research publications')
        snapshots[m][day]=dict(batch=entry['batch'],block=block)
    diagnostics={}
    for m in markets:
        seen=snapshots[m]
        missing=[day for day in expected[m] if day not in seen]
        diagnostics[m]=dict(missing_daily_signal_batches=missing,verified_sessions=sorted(seen))
        if m=='TW':
            diagnostics[m]['missing_filing_evidence_by_session']={
                day:sum(not stock['evaluation']['filingVerified'] or not stock['financial'].get('filingEvidence')
                        for stock in row['block']['stocks'])
                for day,row in seen.items() if day in expected[m]}
    diagnostics['rejected_envelopes']=rejected
    return snapshots,diagnostics


def extend_account(run, checkpoint, end):
    """Advance a sealed account after its separate PIT evidence gate passes.

    run must be bound to the original engine and validated daily signal and
    execution-price inputs. It returns only the requested incremental rows.
    """
    prior=checkpoint['summary']
    market,variant=prior['market'],prior['variant']
    previous=pd.Timestamp(prior['through'])
    end=pd.Timestamp(end)
    if end<=previous:
        return None
    result=run(previous+pd.Timedelta(days=1),end,variant,restore(checkpoint['state'],market))
    daily,second,third,positions,last,state=result
    closed,orders,rejects=(second,third,None) if market=='US' else (third,second,last)
    if daily.index[0]<=previous or daily.index[-1]!=end or not daily.index.is_unique or not daily.index.is_monotonic_increasing:
        raise ValueError('Primary replay returned an invalid date range')
    peak,mdd=prior['peak_nav'],prior['max_drawdown']
    for value in daily.nav:
        if not pd.notna(value) or value<=0:
            raise ValueError('Primary account NAV unavailable')
        peak=max(peak,value)
        mdd=min(mdd,value/peak-1)
    sessions=prior['sessions']+len(daily)
    if state['sessions']!=sessions:
        raise ValueError('Primary session count mismatch')
    if len(orders) and (orders.duplicated(['date','symbol','action']).any() or
                        (pd.to_datetime(orders.signal_date)>=pd.to_datetime(orders.date)).any()):
        raise ValueError('Duplicate or forward-dated primary trade')
    cash=state['cash']
    amount=float(daily['nav_usd' if market=='US' else 'nav_twd'].iloc[-1])
    if abs(cash+(positions.market_value.sum() if len(positions) else 0.)-amount)>1e-5 or cash<-.00001 or daily.core_positions.max()>10:
        raise ValueError('Primary ledger fails reconciliation')
    if variant=='A' and daily.positions.max()>10:
        raise ValueError('Primary A position limit exceeded')
    summary=prior|dict(through=str(end.date()),sessions=sessions,cumulative=float(daily.nav.iloc[-1]-1),
        cagr=float(daily.nav.iloc[-1]**(252/sessions)-1) if sessions>=252 else None,
        max_drawdown=float(mdd),peak_nav=float(peak),cash=cash,nav=amount,positions=len(positions),
        closed=prior['closed']+len(closed),orders=prior['orders']+len(orders))
    return dict(summary=summary,state=state,daily=daily,orders=orders,closed=closed,positions=positions,rejected=rejects)
